def _round(value: Optional[float], digits: int = 3) -> Optional[float]:
    return None if value is None or not np.isfinite(value) else round(float(value), digits)


def _percentile(values: np.ndarray, share: float) -> Optional[float]:
    return float(np.percentile(values, share)) if values.size else None


def analyse_case(case: Dict[str, str], model: str, recompute: bool = False,
                 echo=None) -> Dict[str, Any]:
    """Score one run. Returns its case row, its per-segment rows and its notes."""
    ndimage = _ndimage()
    spacing = METRIC_SPACING_MM
    notes: List[str] = []
    label = case["subject"] or case["run"]
    folders = read_scene(case["scene_dir"])

    pieces = [(name, path) for name, path in folders.get(FIBULA_FOLDER, [])
              if os.path.isfile(path)]
    if not pieces:
        raise RuntimeError('no "%s" models in the saved scene' % FIBULA_FOLDER)

    truth = ground_truth(case, folders, model, recompute=recompute, echo=echo)
    graft_vertices, graft_faces = truth["mesh"]
    if len(graft_faces) == 0:
        raise RuntimeError("the predicted graft has no surface")

    meshes = [(name, read_mesh(path)) for name, path in pieces]
    lower = np.min([graft_vertices.min(axis=0)]
                   + [mesh[0].min(axis=0) for _n, mesh in meshes], axis=0)
    upper = np.max([graft_vertices.max(axis=0)]
                   + [mesh[0].max(axis=0) for _n, mesh in meshes], axis=0)
    shape, affine = grid_for(np.array([lower, upper]), spacing, margin=GRID_MARGIN_MM)

    reference = voxelize(graft_vertices, graft_faces, shape, affine)
    piece_masks = [(name, voxelize(vertices, faces, shape, affine))
                   for name, (vertices, faces) in meshes]
    fibula = np.zeros(shape, bool)
    for _name, mask in piece_masks:
        fibula = np.logical_or(fibula, mask)
    if not reference.any() or not fibula.any():
        raise RuntimeError("the graft or the fibula rasterised to nothing")

    open_edges = sum(geometry_io.mesh_open_edges(faces) for _n, (_v, faces) in meshes)
    if open_edges:
        notes.append("%d open edge(s) across the fibula pieces after welding -- "
                     "their volumes are the enclosed part only" % open_edges)

    stumps = None
    stump_path = folder_entry(folders, CUT_BONES_FOLDER, RESECTED_MANDIBLE_NAME)
    if stump_path and os.path.isfile(stump_path):
        stumps = voxelize(*read_mesh(stump_path), shape=shape, affine=affine)

    intersection = float(np.logical_and(reference, fibula).sum())
    reference_voxels = float(reference.sum())
    fibula_voxels = float(fibula.sum())
    outside = np.logical_and(fibula, ~reference)

    scan = contour_scan(reference, fibula, spacing)
    signed, points = scan["signed"], scan["points"]
    found = np.isfinite(signed)
    if stumps is not None and stumps.any():
        distance_to_stump = ndimage.distance_transform_edt(~stumps) * spacing
        mating = distance_to_stump[points[:, 0].astype(np.int64),
                                   points[:, 1].astype(np.int64),
                                   points[:, 2].astype(np.int64)] <= MATING_FACE_MM
    else:
        mating = np.zeros(len(points), bool)
        notes.append("the remaining mandible was not in the scene, so the "
                     "osteotomy faces could not be separated from the outer contour")
    outer = ~mating
    outer_found = outer & found
    outer_values = signed[outer_found]

    to_reference = ndimage.distance_transform_edt(~reference) * spacing
    to_fibula = ndimage.distance_transform_edt(~fibula) * spacing
    reference_surface, fibula_surface = surface_of(reference), surface_of(fibula)
    reference_to_fibula = to_fibula[reference_surface]
    fibula_to_reference = to_reference[fibula_surface]

    row: Dict[str, Any] = {
        "case": label,
        "run": case["run"],
        "segments": len(meshes),
        "gt_volume_cm3": _round(volume_cm3(reference, spacing), 2),
        "fibula_volume_cm3": _round(volume_cm3(fibula, spacing), 2),

        "volume_ratio_pct": _round(100.0 * intersection / max(reference_voxels, 1.0), 1),
        "contour_error_mm": _round(float(np.abs(outer_values).mean())
                                   if outer_values.size else None),
        "max_projection_mm": _round(float(outer_values.max())
                                    if outer_values.size else None),

        "projection_p95_mm": _round(_percentile(outer_values, 95)),
        "median_offset_mm": _round(float(np.median(outer_values))
                                   if outer_values.size else None),
        "contour_coverage_pct": _round(100.0 * outer_found.sum()
                                       / max(int(outer.sum()), 1), 1),
        "saturated_samples": int((scan["saturated"] & outer).sum()),

        "dice": _round(2.0 * intersection / max(reference_voxels + fibula_voxels, 1.0)),
        "surface_mean_mm": _round(0.5 * (float(reference_to_fibula.mean())
                                         + float(fibula_to_reference.mean()))),
        "hd95_mm": _round(max(_percentile(reference_to_fibula, 95) or 0.0,
                              _percentile(fibula_to_reference, 95) or 0.0)),
        "gt_covered_2mm_pct": _round(100.0 * float((reference_to_fibula
                                                    <= COVERAGE_MM).mean()), 1),
        "fibula_on_gt_2mm_pct": _round(100.0 * float((fibula_to_reference
                                                      <= COVERAGE_MM).mean()), 1),
        "overfill_pct": _round(100.0 * float(outside.sum()) / max(reference_voxels, 1.0), 1),
        "outside_gt_cm3": _round(volume_cm3(outside, spacing), 2),
    }
    row.update({key: _round(value) for key, value
                in slice_dice_loss(reference, fibula, affine, spacing).items()})

    specimen = None
    for _name, path in folders.get(SPECIMEN_FOLDER, []):
        if not os.path.isfile(path):
            continue
        piece = voxelize(*read_mesh(path), shape=shape, affine=affine)
        specimen = piece if specimen is None else np.logical_or(specimen, piece)
    if specimen is not None and specimen.any():
        overlap = float(np.logical_and(reference, specimen).sum())
        row["specimen_volume_cm3"] = _round(volume_cm3(specimen, spacing), 2)
        row["gt_vs_specimen_dice"] = _round(
            2.0 * overlap / max(reference_voxels + float(specimen.sum()), 1.0))

    lengths = segment_lengths(folders)
    planned = [lengths[index] for index in sorted(lengths)]
    row["segment_lengths_mm"] = ", ".join("%.1f" % value for value in planned) or None
    row["total_graft_length_mm"] = _round(sum(planned), 1) if planned else None

    row["gt_source"] = truth.get("source")
    row["gt_orientation"] = truth.get("orientation") or truth.get("declared_orientation")
    row["gt_orientation_score"] = _round(truth.get("orientation_score"))
    row["open_edges"] = open_edges
    row["prediction_s"] = truth.get("seconds")

    if row["gt_volume_cm3"] and row["gt_volume_cm3"] > PLAUSIBLE_GRAFT_CM3:
        notes.append("the predicted graft is %.0f cm3, larger than any mandibular "
                     "graft -- treat this case's ground truth as suspect"
                     % row["gt_volume_cm3"])
    detected = truth.get("detected_orientation")
    declared = truth.get("declared_orientation") or truth.get("orientation")
    if detected and declared and detected != declared:
        notes.append("the file declares %s but the anatomy looks like %s (%.3f); "
                     "the declaration was used" % (declared.upper(), detected.upper(),
                                                   truth.get("orientation_score") or 0.0))
    row["status"] = "; ".join(notes) or None

    segment_rows: List[Dict[str, Any]] = []
    for index, (name, mask) in enumerate(piece_masks):
        piece_surface = surface_of(mask)
        protrusion = to_reference[np.logical_and(mask, ~reference)]
        vertices, faces = meshes[index][1]
        extent = _principal_extent(vertices)
        # The piece's OWN number, not its position in the list, and no fallback
        # to the position: the S<n> length markups are keyed on that number, and
        # the two only coincide while the pieces run 0..N-1 with none missing. A
        # plan that lost a piece would otherwise shift every length up by one --
        # and a blank cell is the honest answer where no markup matches.
        segment_rows.append({
            "case": label,
            "segment": name,
            "length_mm": _round(lengths.get(_trailing_index(name)[0]), 1),
            "measured_length_mm": _round(extent, 1),
            "volume_cm3": _round(volume_cm3(mask, spacing), 2),
            "share_of_fibula_pct": _round(100.0 * float(mask.sum())
                                          / max(fibula_voxels, 1.0), 1),
            "inside_gt_pct": _round(100.0 * float(np.logical_and(mask, reference).sum())
                                    / max(float(mask.sum()), 1.0), 1),
            "protrusion_max_mm": _round(float(protrusion.max()) if protrusion.size else 0.0),
            "protrusion_p95_mm": _round(_percentile(protrusion, 95) or 0.0),
            "surface_to_gt_mm": _round(float(to_reference[piece_surface].mean())),
            "open_edges": geometry_io.mesh_open_edges(faces),
        })

    return {"row": row, "segments": segment_rows, "notes": notes,
            "grid": tuple(int(s) for s in shape)}


def _principal_extent(vertices: np.ndarray) -> Optional[float]:
    """Length of a fibula piece along its own long axis."""
    vertices = np.asarray(vertices, dtype=np.float64)
    if len(vertices) < 3:
        return None
    centred = vertices - vertices.mean(axis=0)
    axis = np.linalg.svd(centred, full_matrices=False)[2][0]
    projected = centred @ axis
    return float(projected.max() - projected.min())


