def _repair_module():
    """The vendored deploy script, imported lazily (it needs scipy)."""
    _ensure("scipy", "scipy")
    from . import mandible_repair                            # noqa: PLC0415
    return mandible_repair


def grid_for(bounds: np.ndarray, spacing: float = METRIC_SPACING_MM,
             margin: float = 0.0) -> Tuple[Tuple[int, int, int], np.ndarray]:
    return _repair_module().grid_for_bounds(np.asarray(bounds, dtype=np.float64),
                                            spacing, margin=margin)


def voxelize(vertices: np.ndarray, faces: np.ndarray,
             shape: Sequence[int], affine: np.ndarray) -> np.ndarray:
    """Solid mask of a surface on one grid: ray parity along all three axes.

    ``mandible_repair._voxelize_fallback`` is called rather than copied. It is a
    frozen vendored file, and a second copy of a subtle rasteriser is a second
    thing to keep correct -- the same reason ``cranial.py`` imports orbital's
    splicer instead of re-implementing it. The sweep is the part that is ours:
    the shipped function fills along axis 0 only, and a ray whose crossing count
    is odd (a hole, a grazed edge) is skipped rather than filled, so a sweep
    along the other two axes recovers those columns without ever adding a voxel
    that a good ray did not enclose.
    """
    repair = _repair_module()
    spacing = float(np.diag(np.asarray(affine, dtype=np.float64))[0])
    vertices = np.asarray(vertices, dtype=np.float64)
    faces = np.asarray(faces, dtype=np.int64)
    mask: Optional[np.ndarray] = None
    for permutation in _SWEEP_AXES:
        inverse = np.argsort(permutation)
        permuted_affine = np.eye(4, dtype=np.float64)
        permuted_affine[:3, :3] = np.diag([spacing] * 3)
        permuted_affine[:3, 3] = np.asarray(affine)[:3, 3][list(permutation)]
        swept = repair._voxelize_fallback(                   # noqa: SLF001
            np.ascontiguousarray(vertices[:, list(permutation)]), faces,
            tuple(int(shape[axis]) for axis in permutation), permuted_affine)
        swept = np.transpose(swept, inverse)
        mask = swept if mask is None else np.logical_or(mask, swept)
    return mask if mask is not None else np.zeros(tuple(int(s) for s in shape), bool)


def surface_of(mask: np.ndarray) -> np.ndarray:
    """Voxels of ``mask`` with a face neighbour outside it."""
    ndimage = _ndimage()
    return np.logical_and(
        mask, ~ndimage.binary_erosion(mask, ndimage.generate_binary_structure(3, 1)))


def volume_cm3(mask: np.ndarray, spacing: float = METRIC_SPACING_MM) -> float:
    return float(mask.sum()) * spacing ** 3 / 1000.0


