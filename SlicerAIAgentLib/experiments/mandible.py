def discover_cases(experiment_root: str) -> List[Dict[str, str]]:
    """One entry per run folder that was exited with "save"."""
    return _discover_cases(experiment_root, RUNS_SUBDIR, DATASET_SUBDIR)


def case_is_scorable(case: Dict[str, str]) -> bool:
    """Does this run hold both halves of the comparison?"""
    try:
        folders = read_scene(case["scene_dir"])
    except Exception:                                        # noqa: BLE001
        return False
    stump = folder_entry(folders, CUT_BONES_FOLDER, RESECTED_MANDIBLE_NAME)
    cached = os.path.join(case["run_dir"], ANALYSIS_SUBDIR, GT_STL_NAME)
    return bool(folders.get(FIBULA_FOLDER)) and (bool(stump) or os.path.isfile(cached))


def build_report(repository_root: str, progress=None, recompute: bool = False
                 ) -> Dict[str, Any]:
    """Analyse every run. Fail-soft per case, so one bad scene costs one case."""
    experiment_root = os.path.join(repository_root, EXPERIMENT_DIR)
    model = model_path(repository_root)
    cases = discover_cases(experiment_root)
    rows: List[Dict[str, Any]] = []
    segments: List[Dict[str, Any]] = []
    failed: List[str] = []
    log: List[str] = []

    if not cases:
        log.append("No runs found under %s."
                   % os.path.join(experiment_root, RUNS_SUBDIR))
    if not os.path.isfile(model):
        log.append("[!] the shape-completion model is missing (%s), so no ground "
                   "truth can be predicted. Only runs with a cached "
                   "Statistic/analysis/%s can be scored." % (model, GT_STL_NAME))

    for index, case in enumerate(cases):
        label = case["subject"] or case["run"]
        if progress is not None:
            try:
                progress(index, len(cases), label)
            except Exception:                                # noqa: BLE001
                logger.debug("Progress callback failed", exc_info=True)
        logger.info("[BRP] case %d/%d: %s", index + 1, len(cases), label)
        started = time.time()
        try:
            result = analyse_case(case, model, recompute=recompute,
                                  echo=lambda text: log.append("   %s" % text))
        except Exception as exc:                             # noqa: BLE001
            log.append("%s: FAILED -- %s" % (label, exc))
            logger.warning("Mandible analysis failed for %s", label, exc_info=True)
            failed.append(label)
            continue
        rows.append(result["row"])
        segments.extend(result["segments"])
        row = result["row"]
        log.append("%s: %d segment(s), Rv %s%%, Ec %s mm over %s%% of the contour, "
                   "Ep %s mm  [grid %s, %.1f s]"
                   % (label, row["segments"], row["volume_ratio_pct"],
                      row["contour_error_mm"], row["contour_coverage_pct"],
                      row["max_projection_mm"], "x".join(str(s) for s in result["grid"]),
                      time.time() - started))
        for note in result["notes"]:
            log.append("   [!] %s: %s" % (label, note))

    timing_rows, step_rows = collect_timing(cases, log)
    timing_title, timing_blocks = timing_sheet(timing_rows, step_rows)
    summary = summary_rows(rows)

    sheets = [
        ("Reconstruction accuracy", [
            ("One row per run. The plan's fibula segments are scored against the "
             "healthy mandible segment predicted for that patient's own defect. "
             "Rv, Ec and Ep are the three metrics Guo et al. (Medical Image "
             "Analysis 102 (2025) 103544, section 4.2) take from Nakao et al. "
             "(IEEE TBME 64(8):1772, 2017); the rest is the geometry behind them.",
             CASE_COLUMNS, rows),
            ("Per fibula segment: which piece carries the fit and which one "
             "stands proud.", SEGMENT_COLUMNS, segments),
            ("Across every scored run.", SUMMARY_COLUMNS, summary),
            ("DEFINITIONS -- how the measurement is made",
             DEFINITION_COLUMNS, definition_rows(METHOD_DEFINITIONS)),
            ("DEFINITIONS -- per-run columns",
             DEFINITION_COLUMNS, definition_rows(CASE_DEFINITIONS)),
            ("DEFINITIONS -- per-segment columns",
             DEFINITION_COLUMNS, definition_rows(SEGMENT_DEFINITIONS)),
        ]),
        (timing_title, list(timing_blocks)),
    ]
    return {"sheets": sheets, "log": log, "rows": rows, "segments": segments,
            "summary": summary, "timing_rows": timing_rows, "step_rows": step_rows,
            "cases": len(cases), "analysed": len(rows), "failed_cases": failed,
            "model": model, "model_present": os.path.isfile(model)}


def run_analysis(repository_root: str, progress=None, recompute: bool = False
                 ) -> Dict[str, Any]:
    """Analyse every run and write the workbook. Returns the report + its path."""
    from .workbook import write_workbook                     # noqa: PLC0415

    report = build_report(repository_root, progress=progress, recompute=recompute)
    output = os.path.join(repository_root, EXPERIMENT_DIR, RUNS_SUBDIR, WORKBOOK_NAME)
    written, notes = write_workbook(output, report["sheets"])
    report["workbook"] = written
    report["log"].extend(notes)
    try:
        report["workbook_relative"] = os.path.relpath(written, repository_root)
    except ValueError:
        report["workbook_relative"] = written
    return report
