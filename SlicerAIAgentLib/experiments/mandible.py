def _storage_files(root: ET.Element, scene_dir: str) -> Dict[str, str]:
    """``{storage node id -> path on disk}``.

    ``fileName`` is URL-ESCAPED, and every model this procedure saves has spaces
    in its name -- "Transformed Fibula Segment 0A-0B_15.vtk" is written as
    "Transformed%20Fibula%20Segment%200A-0B_15.vtk". Joining that verbatim gives
    a path that does not exist, and the only symptom is a scene that reports no
    fibula pieces, so the raw name is kept as a fallback rather than as the
    primary: a writer that did not escape is then still read, and a file
    genuinely holding a percent sign survives either way.
    """
    files: Dict[str, str] = {}
    for node in root.iter():
        node_id, name = node.get("id"), node.get("fileName")
        if not node_id or not name:
            continue
        unquoted = os.path.join(scene_dir, unquote(name))
        raw = os.path.join(scene_dir, name)
        files[node_id] = (unquoted if os.path.exists(unquoted)
                          else (raw if os.path.exists(raw) else unquoted))
    return files


def _referenced(node: ET.Element, role: str) -> List[str]:
    """Every node id ``node`` names under ``role``, in both MRML spellings."""
    candidates: List[str] = []
    for entry in (node.get("references") or "").split(";"):
        key, separator, value = entry.partition(":")
        if separator and key.strip() == role:
            candidates.extend(value.split())
    if role == "storage":
        candidates.extend((node.get("storageNodeRef") or "").split())
    return candidates


def read_scene(scene_dir: str) -> Dict[str, Any]:
    """``{folder name -> [(node name, file path), ...]}`` for one saved scene.

    The subject hierarchy is what carries a node's ROLE in this procedure --
    which folder BoneReconstructionPlanner put it in -- and it is the only part
    of the scene this module reads. Everything else about a node (its transform,
    its display) is already baked into the geometry a flat save writes.
    """
    path = os.path.join(scene_dir, "scene.mrml")
    if not os.path.isfile(path):
        raise RuntimeError("no scene.mrml in %s" % scene_dir)
    root = ET.parse(path).getroot()
    storage = _storage_files(root, scene_dir)

    names: Dict[str, str] = {}
    files: Dict[str, str] = {}
    for node in root.iter():
        node_id = node.get("id") or ""
        if not node_id.startswith("vtkMRML") or not node.get("name"):
            continue
        names[node_id] = node.get("name")
        for reference in _referenced(node, "storage"):
            if storage.get(reference):
                files[node_id] = storage[reference]
                break

    items = {item.get("id"): item for item in root.iter("SubjectHierarchyItem")}
    folders: Dict[str, List[Tuple[str, str]]] = {}
    for item in items.values():
        data_node = item.get("dataNode") or ""
        parent = items.get(item.get("parent") or "")
        if not data_node or parent is None:
            continue
        folder = parent.get("name") or names.get(parent.get("dataNode") or "", "")
        name = item.get("name") or names.get(data_node, "")
        if data_node in files:
            folders.setdefault(folder, []).append((name, files[data_node]))
    for entries in folders.values():
        entries.sort(key=lambda entry: _trailing_index(entry[0]))
    return folders


_INDEX = re.compile(r"(\d+)")


def _trailing_index(name: str) -> Tuple[int, str]:
    """Sort key that orders the pieces the way the plan numbers them.

    The first integer in the name is the piece number, so segment 2 sorts before
    segment 10 rather than after it, and the whole name breaks ties -- an
    unnumbered node still lands in a stable place instead of moving with the
    directory listing. This matters because the per-segment rows are read
    alongside the S0/S1/S2 lengths, which are keyed on that number.
    """
    match = _INDEX.search(name or "")
    return (int(match.group(1)) if match else 10 ** 6, name or "")


def folder_entry(folders: Dict[str, List[Tuple[str, str]]], folder: str,
                 name: str) -> Optional[str]:
    for entry_name, path in folders.get(folder, []):
        if entry_name == name:
            return path
    return None


def read_mesh(path: str) -> Tuple[np.ndarray, np.ndarray]:
    """A saved model as a welded triangle mesh. See ``geometry_io.weld_mesh``."""
    return geometry_io.weld_mesh(*geometry_io.read_vtk_mesh(path))


def segment_lengths(folders: Dict[str, List[Tuple[str, str]]]) -> Dict[int, float]:
    """``{piece index -> planned length in mm}`` from the S0/S1/S2 markups.

    The plan's own number, taken from the line BoneReconstructionPlanner drew
    between the two fibula cut planes -- not re-derived from the mesh, which is
    reported separately as ``measured_length_mm`` so the two can be compared.
    """
    out: Dict[int, float] = {}
    for name, path in folders.get(SEGMENT_LENGTH_FOLDER, []):
        match = _INDEX.search(name or "")
        if match is None or not os.path.isfile(path):
            continue
        try:
            points = geometry_io.read_markups_points(path)[0]
        except Exception:                                    # noqa: BLE001
            logger.debug("Unreadable segment-length markup %s", path, exc_info=True)
            continue
        if len(points) >= 2:
            out[int(match.group(1))] = float(np.linalg.norm(points[1] - points[0]))
    return out


