def model_path(repository_root: str) -> str:
    return os.path.join(repository_root, MODEL_RELATIVE)


def predict_graft(vertices: np.ndarray, faces: np.ndarray, model: str,
                  orientation: str, echo=None) -> Dict[str, Any]:
    """The missing mandible segment, as a mesh in the INPUT's own frame.

    This is ``mandible_repair.repair()``'s body with two deliberate changes, and
    the reason for each is in the module docstring:

    * the input is rasterised by ``voxelize`` -- the three-axis ray-parity sweep
      -- rather than by whichever voxeliser ``repair()`` picks, so the answer
      does not depend on whether VTK happens to be importable, and so a partially
      welded Slicer model cannot inflate it; and
    * it takes a mesh and returns a mesh, because the caller already has one and
      an STL round trip in the middle would be a second rasterisation to reason
      about.

    Checked, not assumed: on the reference run this reproduces the shipped
    ``repair()``'s graft bounds exactly (``scripts/check_mandible_analysis.py``).
    """
    repair = _repair_module()
    ndimage = _ndimage()
    _ensure("onnxruntime", "onnxruntime")
    _ensure("skimage", "scikit-image")

    def say(message):
        if echo is not None:
            echo(message)

    vertices = np.asarray(vertices, dtype=np.float64)
    detected, score = repair.detect_orientation(vertices, faces)
    flipped = str(orientation).lower() == "lps"
    if flipped:
        vertices = repair.flip_lps_ras(vertices)

    spacing = METRIC_SPACING_MM
    shape, affine = grid_for(np.array([vertices.min(axis=0), vertices.max(axis=0)]),
                             spacing, margin=12.0)
    fine = repair.keep_large_components(voxelize(vertices, faces, shape, affine))
    if not fine.any():
        raise RuntimeError("the resected mandible rasterised to nothing")
    say("  input bone %.1f cm3 in %d piece(s)"
        % (volume_cm3(fine, spacing),
           ndimage.label(fine, structure=ndimage.generate_binary_structure(3, 3))[1]))

    predictor = repair.Predictor(model)
    window, window_matrix = repair.prepare_input(fine, affine, predictor.network_shape,
                                                 predictor.spacing)
    started = time.time()
    probability = predictor(window)
    say("  network %s in %.1f s" % (str(window.shape), time.time() - started))

    rough = probability > 0.5
    if not rough.any():
        raise RuntimeError("the network predicted an empty graft")
    box = repair.find_boundaries(rough)
    corners = repair.voxel_to_world(
        np.array([[box[0], box[2], box[4]], [box[1] - 1, box[3] - 1, box[5] - 1]],
                 dtype=np.float64), window_matrix)
    out_shape, out_affine = repair.capped_grid(
        np.array([corners.min(axis=0), corners.max(axis=0)]), spacing, 8.0,
        label="graft", echo=False)
    out_spacing = float(repair.spacing_from_affine(out_affine)[0])

    fine_probability = repair.resample_between_grids(probability, window_matrix,
                                                     out_affine, out_shape, order=1)
    fine_bone = repair.resample_between_grids(fine, affine, out_affine, out_shape, order=0)
    graft = repair.clean_prediction(fine_probability, fine_bone, threshold=0.5)
    if not graft.any():
        raise RuntimeError("the graft vanished during post-processing")

    cubic_cm = volume_cm3(graft, out_spacing)
    field = ndimage.gaussian_filter(graft.astype(np.float32), sigma=0.8)
    step = max(int(round((float(graft.sum()) / 1e6) ** (1.0 / 3.0))), 1)
    graft_vertices, graft_faces = repair.volume_to_mesh(field, out_affine, level=0.5,
                                                        smoothing=12, step_size=step)
    if flipped:
        graft_vertices = repair.flip_lps_ras(graft_vertices)
    say("  graft %.1f cm3 at %.2f mm" % (cubic_cm, out_spacing))

    return {
        "vertices": graft_vertices,
        "faces": np.asarray(graft_faces, dtype=np.int64),
        "orientation": "lps" if flipped else "ras",
        "detected_orientation": detected,
        "orientation_score": float(score),
        "graft_volume_cm3": cubic_cm,
        "graft_spacing_mm": out_spacing,
        "input_volume_cm3": volume_cm3(fine, spacing),
    }


def ground_truth(case: Dict[str, str], folders: Dict[str, List[Tuple[str, str]]],
                 model: str, recompute: bool = False, echo=None) -> Dict[str, Any]:
    """The predicted healthy segment for one run, predicting it if needed.

    Cached as an STL inside the run's own ``Statistic/analysis/``, and the STL is
    what the metrics are then taken on -- so the ground truth a reader can load
    into Slicer beside the plan is byte for byte the one that was scored. A
    hidden in-memory mask would be a second ground truth nobody can inspect.
    """
    analysis_dir = os.path.join(case["run_dir"], ANALYSIS_SUBDIR)
    stl_path = os.path.join(analysis_dir, GT_STL_NAME)
    record_path = os.path.join(analysis_dir, PREDICTION_JSON)

    if os.path.isfile(stl_path) and not recompute:
        record = {}
        if os.path.isfile(record_path):
            try:
                record = json.load(io.open(record_path, encoding="utf-8"))
            except Exception:                                # noqa: BLE001
                logger.debug("Unreadable %s", record_path, exc_info=True)
        vertices = geometry_io.read_stl_points(stl_path)
        faces = np.arange(len(vertices), dtype=np.int64).reshape(-1, 3)
        record["source"] = "cached"
        record["stl"] = stl_path
        record["mesh"] = geometry_io.weld_mesh(vertices, faces)
        return record

    source = folder_entry(folders, CUT_BONES_FOLDER, RESECTED_MANDIBLE_NAME)
    if not source or not os.path.isfile(source):
        raise RuntimeError('no "%s/%s" in the saved scene'
                           % (CUT_BONES_FOLDER, RESECTED_MANDIBLE_NAME))
    if not os.path.isfile(model):
        raise RuntimeError("the shape-completion model is missing: %s" % model)

    vertices, faces = read_mesh(source)
    declared = geometry_io.vtk_coordinate_system(source) or "ras"
    started = time.time()
    result = predict_graft(vertices, faces, model, declared, echo=echo)
    result["seconds"] = round(time.time() - started, 2)
    result["declared_orientation"] = declared
    result["source"] = "predicted"
    result["model"] = os.path.basename(model)
    result["model_bytes"] = os.path.getsize(model)
    result["input_model"] = os.path.basename(source)

    os.makedirs(analysis_dir, exist_ok=True)
    repair = _repair_module()
    repair.save_stl(vertices, faces, os.path.join(analysis_dir, INPUT_STL_NAME))
    repair.save_stl(result["vertices"], result["faces"], stl_path)
    result["stl"] = stl_path
    result["mesh"] = geometry_io.weld_mesh(result["vertices"], result["faces"])
    try:
        # Basenames, not the paths this machine happened to use: a run folder is
        # copied, shared and attached to a paper, and an absolute path inside it
        # is both noise and a small leak of where it was produced.
        record = {key: value for key, value in result.items()
                  if key not in ("vertices", "faces", "mesh")}
        record["stl"] = GT_STL_NAME
        io.open(record_path, "w", encoding="utf-8").write(
            json.dumps(record, indent=2, default=str))
    except Exception:                                        # noqa: BLE001
        logger.debug("Could not write %s", record_path, exc_info=True)
    return result


# ---------------------------------------------------------------------------
# The contour scan -- Nakao III-B-2 and eq. 8
# ---------------------------------------------------------------------------

def contour_scan(reference: np.ndarray, fibula: np.ndarray, spacing: float
                 ) -> Dict[str, np.ndarray]:
    """Signed local shape distance at every point of the reference surface.

    Nakao's steps 1-4, with two departures, each stated because each changes
    what the number is:

    * **3D, not tangent-plane slices.** Nakao contours the mandible on slices
      parallel to a mandibular tangent plane and scans in-plane. That plane
      belongs to the mandibular coordinate system this analysis deliberately
      does not build (see the module docstring on Er). Sampling the surface
      itself and using its own outward normal is the direct generalisation and
      needs no such frame.
    * **The scan walks away from the sample, not inward from a fixed ring.**
      Nakao starts at a point expanded outside the mandible and marches in,
      taking the first fibula surface met. Where the two agree -- which is
      everywhere the geometry is not degenerate -- they find the same crossing.
      Where they do not is a concavity: a normal pointing across the arch meets
      the fibula on the FAR side first, and an outside-in march reports that as
      a 15 mm protrusion. Walking outward from the sample until the fibula ends
      (if it covers the sample) or inward until it begins (if it does not)
      cannot: it always returns the fibula surface nearest the sample, which is
      what a *local* shape distance means.

    Sign: positive = the fibula surface lies outside the native contour (a
    protrusion, the thing ``Ep`` measures), negative = inside it (a depression).
    ``signed`` is NaN where the scan found nothing within range -- Nakao's own
    terminated scan -- and ``saturated`` marks samples the fibula covers for the
    whole outward range, whose protrusion is only known to be >= SCAN_OUT_MM.

    The crossing is read off the fibula's SIGNED DISTANCE FIELD rather than by
    asking whether the nearest voxel is set, and that is worth two sentences
    because it is where a systematic error lives. A boolean lookup flips at the
    midplane between two voxel centres, so it quantises every reading to the
    step grid and breaks ties in whichever direction ``rint`` happens to round
    -- on a flat face that showed up as -1.75 mm on one side of a slab and
    -2.00 mm on the other, for the same 2 mm gap. The field's zero level is the
    voxel face itself, so interpolating the sign change is sub-voxel and
    direction-symmetric.

    Then the whole thing is shifted by HALF A VOXEL, once: the scan starts at a
    surface voxel's CENTRE while the surface that voxel represents is half a
    voxel further out. Without the correction two identical masks read +0.25 mm
    apart rather than flush, and a 3.0 mm protrusion reads 3.25.
    """
    ndimage = _ndimage()
    inside = ndimage.distance_transform_edt(reference) * spacing
    outside = ndimage.distance_transform_edt(~reference) * spacing
    normals = np.stack(np.gradient(ndimage.gaussian_filter(outside - inside, 1.0),
                                   spacing), axis=-1)

    surface = surface_of(reference)
    points = np.argwhere(surface).astype(np.float64)
    if len(points) == 0:
        return {"signed": np.zeros(0), "saturated": np.zeros(0, bool),
                "points": points}
    direction = normals[surface]
    direction = direction / np.maximum(
        np.linalg.norm(direction, axis=-1), 1e-9)[:, None]

    # Positive outside the fibula, negative inside it, zero on its surface.
    field = (ndimage.distance_transform_edt(~fibula)
             - ndimage.distance_transform_edt(fibula)) * spacing
    far = float(max(SCAN_OUT_MM, SCAN_IN_MM) + spacing)

    def sample(offset: float) -> np.ndarray:
        """``field`` along each ray, ``far`` (i.e. "outside") off the grid."""
        position = (points + direction * (offset / spacing)).T
        return ndimage.map_coordinates(field, position, order=1, mode="constant",
                                       cval=far)

    def walk(active: np.ndarray, sign: float, reach: float
             ) -> Tuple[np.ndarray, np.ndarray]:
        """First zero crossing along ``sign`` * normal, for the ``active`` rays."""
        crossing = np.full(len(points), np.nan)
        pending = active.copy()
        previous_offset = 0.0
        previous = sample(0.0)
        for offset in np.arange(SCAN_STEP_MM, reach + 1e-9, SCAN_STEP_MM):
            if not pending.any():
                break
            current = sample(sign * offset)
            crossed = pending & ((previous <= 0.0) != (current <= 0.0))
            if crossed.any():
                # Linear in the field, which is a distance: exact for a plane.
                gap = previous[crossed] - current[crossed]
                share = np.where(np.abs(gap) > 1e-12, previous[crossed] / gap, 0.0)
                crossing[crossed] = sign * (previous_offset
                                            + share * (offset - previous_offset))
                pending &= ~crossed
            previous_offset, previous = offset, current
        return crossing, pending

    covered = sample(0.0) <= 0.0

    # Covered: walk outward until the fibula ends -- how far it stands proud.
    outward, unresolved = walk(covered, 1.0, SCAN_OUT_MM)
    saturated = unresolved & covered
    outward[saturated] = SCAN_OUT_MM

    # Not covered: walk inward until the fibula begins.
    inward = walk(~covered, -1.0, SCAN_IN_MM)[0]

    signed = np.where(covered, outward, inward) - 0.5 * spacing
    return {"signed": signed, "saturated": saturated, "points": points}


# ---------------------------------------------------------------------------
# The slice-weighted Dice objective -- Guo et al. eqs. 4-5
# ---------------------------------------------------------------------------

def _oriented_frame(mask: np.ndarray, affine: np.ndarray, spacing: float
                    ) -> Optional[np.ndarray]:
    """The grafted segments' own oriented bounding box, as a 3x3 basis.

    Guo et al. 3.5: the slices are cut in the OBB frame of the grafted bone so
    "the grafted bone segments have the maximum projected area". Axis 0 is the
    fibula's long direction, which is what makes the xy and xz families the two
    the paper distinguishes.
    """
    points = np.argwhere(mask).astype(np.float64)
    if len(points) < 3:
        return None
    world = points * spacing + np.asarray(affine)[:3, 3]
    centred = world - world.mean(axis=0)
    basis = np.linalg.svd(centred, full_matrices=False)[2]
    if np.linalg.det(basis) < 0:
        basis[2] *= -1.0
    return basis


def slice_dice_loss(reference: np.ndarray, fibula: np.ndarray, affine: np.ndarray,
                    spacing: float) -> Dict[str, Optional[float]]:
    """Guo et al. eq. 4 on both slice families, and eq. 5's weighted sum.

    Per slice, Dice between the fibula's pixels and the reference's; each slice
    weighted by its own reference-pixel count, so the thin marginal slices --
    where a fibula rod cannot help being a poor match for a mandible -- cannot
    dominate. The slices span the FIBULA's extent, which is what the paper means
    by "the total number of 2D slices in the current planning scheme".
    """
    ndimage = _ndimage()
    basis = _oriented_frame(fibula, affine, spacing)
    if basis is None:
        return {"slice_loss_xy": None, "slice_loss_xz": None, "slice_loss_total": None}

    origin = np.asarray(affine)[:3, 3]
    both = np.logical_or(reference, fibula)
    corners = np.argwhere(both).astype(np.float64) * spacing + origin
    local = corners @ basis.T
    low, high = local.min(axis=0) - SLICE_MM, local.max(axis=0) + SLICE_MM
    counts = np.maximum(np.ceil((high - low) / SLICE_MM).astype(np.int64) + 1, 2)

    axes = [np.arange(counts[axis], dtype=np.float32) * SLICE_MM + low[axis]
            for axis in range(3)]
    grid = np.meshgrid(*axes, indexing="ij")
    stacked = np.stack([grid[0], grid[1], grid[2]], axis=-1)
    world = stacked @ basis
    voxel = [(world[..., axis] - origin[axis]) / spacing for axis in range(3)]
    sampled = [ndimage.map_coordinates(source.astype(np.uint8), voxel, order=0,
                                       mode="constant", cval=0) > 0
               for source in (reference, fibula)]
    aligned_reference, aligned_fibula = sampled

    def loss(axis: int) -> Optional[float]:
        others = tuple(a for a in range(3) if a != axis)
        reference_count = aligned_reference.sum(axis=others).astype(np.float64)
        fibula_count = aligned_fibula.sum(axis=others).astype(np.float64)
        overlap = np.logical_and(aligned_reference,
                                 aligned_fibula).sum(axis=others).astype(np.float64)
        # "The height is based on the fibula segments": the slices are the ones
        # the plan SPANS, which is the interval between its first and last, not
        # only the ones it happens to occupy. A slice inside that span with no
        # fibula in it is a gap between two pieces and must count against the
        # plan, not vanish from the average.
        occupied = np.flatnonzero(fibula_count > 0)
        if occupied.size == 0:
            return None
        spanned = np.zeros(len(fibula_count), bool)
        spanned[occupied[0]:occupied[-1] + 1] = True
        weight = reference_count * spanned
        if weight.sum() <= 0:
            return None
        denominator = np.maximum(reference_count + fibula_count, 1.0)
        dice = 2.0 * overlap / denominator
        return float(1.0 - float((dice * weight).sum()) / float(weight.sum()))

    # xy slices step along the third OBB axis, xz slices along the second.
    xy, xz = loss(2), loss(1)
    total = None if xy is None or xz is None else xy + SLICE_XZ_WEIGHT * xz
    return {"slice_loss_xy": xy, "slice_loss_xz": xz, "slice_loss_total": total}


