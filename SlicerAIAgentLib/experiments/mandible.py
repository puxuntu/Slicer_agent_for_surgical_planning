"""BoneReconstructionPlanner: how well do the fibula segments restore the mandible?

A run of this procedure saves two things this analysis needs, and neither of
them is the answer:

* ``Cut Bones/Resected mandible`` -- the patient's mandible with the tumour
  segment removed, i.e. the two remaining stumps; and
* ``Transformed Fibula Pieces/Transformed Fibula Segment <n>A-<n>B`` -- the
  osteotomised fibula, each piece already carrying the transform that seats it
  in the defect.

What is missing is the thing the plan is trying to reproduce: the **healthy
bone that used to be where the defect is**. It is not in the scan -- it was
removed with the tumour, and the specimen the surgeon took out
(``Cut Mandible Pieces/Mandible Segment <n>``) is the diseased bone, expanded
or eroded by the lesion, which is exactly why the plan is not aiming at it. So
the ground truth is PREDICTED: ``mandible_repair.py`` (vendored beside this
file, with ``Resources/Models/mandible_repair.onnx``) completes the resected
mandible with a shape-completion U-Net and returns the missing segment alone.
That is the same premorbid-shape step Guo et al. use, and for the same reason
they give: mirroring the healthy side cannot be trusted (a mandible is not
symmetric) and cannot be done at all across the midline.

Two papers define what is measured, and the second adopts the first's metrics
verbatim, so the three headline numbers here are theirs:

* Nakao et al., *Automated Planning With Multivariate Shape Descriptors for
  Fibular Transfer in Mandibular Reconstruction*, IEEE TBME 64(8):1772-1783,
  2017 -- the shape distance ``Es`` (III-B-2) and the projection ``Ep``
  (eq. 8), both taken by scanning the native mandible's contour normals onto
  the transferred fibula.
* Guo et al., *Automated planning of mandible reconstruction with fibula free
  flap based on shape completion and morphometric descriptors*, Medical Image
  Analysis 102 (2025) 103544 -- section 4.2 evaluates three metrics "proposed
  by Nakao et al.": volume ratio ``Rv``, contour error ``Ec`` (= Nakao's
  ``Es``) and maximum projection ``Ep``; and section 3.5 defines the
  slice-weighted Dice objective (eqs. 4-5) reported here beside them.

Guo et al. also settle the question this module would otherwise have to answer
for itself: having no complete mandible for the plans they compare against,
they "utilized the predicted complete mandibular shape generated by Stage I of
our method as the patient's reference mandible". That is precisely the
arrangement here, and it is why the predicted segment is a legitimate ground
truth rather than a convenience.

NOT computed, and named rather than approximated
------------------------------------------------
Nakao's second descriptor, the **mirror-symmetric distance Er** (III-B-3), is
absent. It is not a distance between the graft and a reference: it compares the
reconstructed mandible's left half against its own mirrored right half, so it
needs the contralateral mandible AND the mandibular coordinate system that
III-B-1 builds from a tangent plane and a visually located midline. Both are
outside what the graft and the fibula can answer, and the midline step is the
one Guo et al. single out as unreliable. A number produced from a guessed
midline would look like the paper's and mean something else.

Frames
------
Every ``.vtk`` a run saves declares ``SPACE=LPS`` in its own header, and they
all agree with each other, so nothing here is converted -- the metrics are
distances and overlaps, which no orthogonal mirror can change. The ONE place
the frame matters is the network, which works in RAS: the graft is predicted
with the file's declared convention rather than with the script's anatomical
heuristic, and the heuristic is run anyway and recorded beside it, because a
mandible fed in mirrored produces a confident graft built for the other side of
the head and nothing downstream would object.

Meshes
------
Everything is measured on ONE voxel grid at ``METRIC_SPACING_MM``, built by one
voxeliser, for the reason ``orbital.py`` uses one meshing pipeline for all three
of its surfaces: a distance between two surfaces produced by different rules
measures the rules. That voxeliser is ray parity (``mandible_repair``'s own
VTK-free path), swept along all three axes and unioned, and that is not a
preference:

* Slicer's plane-cut models are **partially welded** -- the cut wall and its cap
  meet at points stored twice -- and ``vtkPolyDataToImageStencil`` on such a mesh
  over-fills the resected mandible by 4% and under-fills a cut fibula segment by
  38%. Both come back as a plausible volume. On the reference case the inflated
  mandible made the completion network predict a 45 cm3 blob where the correct
  input gives a 19 cm3 graft, so this is not a rounding difference.
* Ray parity treats each triangle independently and is immune to that, and after
  welding it agrees with VTK's stencil to 0.001 cm3 on every piece of the
  reference runs, including one that carries a genuine 44-edge hole -- which is
  what the three-axis union is for. A ray whose crossing count comes out odd is
  skipped rather than filled, so a hole costs the columns that pass through it
  and a sweep along another axis recovers them.

``mesh_open_edges`` is reported per case for what remains: after welding, an
open edge is a real hole, and a leaking piece is a volume that cannot be trusted.

Slicer-free, so ``scripts/check_mandible_analysis.py`` runs the whole thing --
reader, voxeliser, contour scan, every metric -- outside Slicer against the
saved runs.
"""

