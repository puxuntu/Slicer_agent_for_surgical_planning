def definition_rows(pairs: Sequence[Tuple[str, str]]) -> List[Dict[str, str]]:
    return [{"term": term, "definition": text} for term, text in pairs]


def summary_rows(rows: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    for column, digits, note in SUMMARY_METRICS:
        values = [float(row[column]) for row in rows
                  if isinstance(row.get(column), (int, float))]
        if not values:
            continue
        array = np.asarray(values, dtype=float)
        out.append({
            "metric": column,
            "n": len(values),
            "mean": round(float(array.mean()), digits),
            "sd": round(float(array.std(ddof=1)), digits) if array.size > 1 else 0.0,
            "min": round(float(array.min()), digits),
            "median": round(float(np.median(array)), digits),
            "max": round(float(array.max()), digits),
            "note": note or None,
        })
    return out


