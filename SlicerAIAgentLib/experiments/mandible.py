def _ensure(module: str, package: str):
    """Import ``module``, pip-installing ``package`` through Slicer if needed."""
    try:
        return __import__(module)
    except ImportError:
        pass
    try:
        import slicer                                        # noqa: PLC0415
        slicer.util.pip_install(package)
        return __import__(module)
    except Exception as exc:                                 # noqa: BLE001
        raise RuntimeError(
            "%s is required for the mandible analysis and could not be "
            "installed (%s). Install it into Slicer's Python and try again."
            % (package, exc))


def _ndimage():
    _ensure("scipy.ndimage", "scipy")
    from scipy import ndimage                                # noqa: PLC0415
    return ndimage


